function translatePage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  localStorage.setItem('dh_lang', lang);

  // Update toggle button text
  const toggleBtn = document.getElementById('langToggle');
  if (toggleBtn) {
    toggleBtn.textContent = lang === 'ar' ? 'English' : 'عربي';
  }

  // Walk DOM to translate text nodes
  function walkNodes(node) {
    if (node.nodeType === 3) {
      let txt = node.nodeValue.trim();
      if (txt) {
        if (!node.originalEn) node.originalEn = txt;
        
        let targetText = node.originalEn;
        if (lang === 'ar' && arDict[node.originalEn]) {
          targetText = arDict[node.originalEn];
        }
        
        if (node.nodeValue.trim() !== targetText) {
           node.nodeValue = node.nodeValue.replace(node.nodeValue.trim(), targetText);
        }
      }
    } else if (node.nodeType === 1 && !['SCRIPT', 'STYLE'].includes(node.tagName)) {
      // Check placeholders
      if (node.placeholder) {
        if (!node.originalPlaceholder) node.originalPlaceholder = node.placeholder;
        node.placeholder = (lang === 'ar' && arDict[node.originalPlaceholder]) 
          ? arDict[node.originalPlaceholder] 
          : node.originalPlaceholder;
      }
      
      // Specifically avoid translating `.ar-text` elements that are already Arabic
      if (node.classList.contains('ar-text') || node.classList.contains('dish-card__name-ar') || node.classList.contains('cat-tab__ar')) {
        return; 
      }
      
      node.childNodes.forEach(walkNodes);
    }
  }
  
  walkNodes(document.body);
}

function applyInitialLang() {
  const savedLang = localStorage.getItem('dh_lang') || 'en';
  if (savedLang === 'ar') {
    setTimeout(() => translatePage('ar'), 50);
  }
}

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', applyInitialLang);
} else {
  applyInitialLang();
}
